"""Summarize versioned ChannelEvidence JSONL outputs without attribution scoring."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import tempfile
from collections import Counter
from pathlib import Path


def read_jsonl(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as stream:
        return [json.loads(line) for line in stream if line.strip()]


def sha256_path(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def summarize(snapshots: dict[str, list[dict]]) -> dict:
    records = [record for batch in snapshots.values() for record in batch]
    handles = {str(record.get("channel", "")).lower().lstrip("@") for record in records
               if record.get("channel")}
    groups = Counter(record.get("legacy_group") or "unknown" for record in records)
    return {
        "schema_version": "1.0",
        "snapshot_count": len(snapshots),
        "snapshot_records": len(records),
        "unique_channels": len(handles),
        "infrastructure_candidate_records": sum(bool(r.get("infrastructure_candidate")) for r in records),
        "origin_unknown_records": sum((r.get("origin") or {}).get("value", "unknown") == "unknown"
                                       for r in records),
        "content_orientation_unknown_records": sum(
            (r.get("content_orientation") or {}).get("value", "unknown") == "unknown" for r in records),
        "legacy_group_records": dict(sorted(groups.items())),
        "per_snapshot": {
            name: {
                "records": len(batch),
                "unique_channels": len({str(r.get("channel", "")).lower().lstrip("@")
                                         for r in batch if r.get("channel")}),
                "infrastructure_candidate_records": sum(bool(r.get("infrastructure_candidate"))
                                                         for r in batch),
            }
            for name, batch in sorted(snapshots.items())
        },
        "interpretation": "Infrastructure candidate counts are review-routing features, not origin, political orientation, state-control, or operation findings.",
    }


def render_markdown(summary: dict, input_receipts: list[dict]) -> str:
    lines = [
        "# Telegram Channel Evidence Candidate Summary",
        "",
        "This report describes versioned candidate-feature exports for the supplied Telegram panel snapshots. It does not attribute channel origin, political orientation, operator, state control, or operational participation.",
        "",
        "## Coverage",
        "",
        f"- Snapshot records: **{summary['snapshot_records']}** across **{summary['snapshot_count']}** files.",
        f"- Distinct channel handles across those snapshots: **{summary['unique_channels']}**.",
        f"- Records with `infrastructure_candidate=true`: **{summary['infrastructure_candidate_records']}**.",
        f"- Origin remains `unknown` for **{summary['origin_unknown_records']}** records.",
        f"- Content orientation remains `unknown` for **{summary['content_orientation_unknown_records']}** records.",
        "",
        "## Per-snapshot counts",
        "",
        "| Snapshot file | Records | Unique handles | Infrastructure candidates |",
        "|---|---:|---:|---:|",
    ]
    for name, values in summary["per_snapshot"].items():
        lines.append(f"| `{name}` | {values['records']} | {values['unique_channels']} | {values['infrastructure_candidate_records']} |")
    lines.extend([
        "",
        "## Inputs and provenance",
        "",
        "| Candidate export | SHA-256 |",
        "|---|---|",
    ])
    for receipt in input_receipts:
        lines.append(f"| `{receipt['path']}` | `{receipt['sha256']}` |")
    lines.extend([
        "",
        "## Interpretation limits",
        "",
        "An infrastructure candidate is generated by public-profile markers or a thresholded share of observed outbound links. These signals can be generated by Ukrainian OSINT and fact-checking channels, quotation, archival references, or other non-attribution explanations. No candidate flag establishes origin or control. Legacy A–U labels are preserved in a separate compatibility field and are not used to fill the new evidence axes.",
        "",
        "**Provenance:** counts are computed by `src/analysis/channel_evidence_summary.py` from the listed JSONL exports. Exports are produced by `src/analysis/channel_evidence.py` from the referenced channel and post snapshots. The underlying panel is purposive and does not represent all Telegram channels.",
        "",
    ])
    return "\n".join(lines)


def write_atomic(path: Path, data: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent, text=True)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(name, path)
    finally:
        Path(name).unlink(missing_ok=True)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", nargs="+", type=Path)
    parser.add_argument("--json", required=True, type=Path, help="Machine-readable summary output")
    parser.add_argument("--markdown", required=True, type=Path, help="Human-readable summary output")
    args = parser.parse_args(argv)
    resolved_inputs = {path.resolve() for path in args.inputs}
    if args.json.resolve() in resolved_inputs or args.markdown.resolve() in resolved_inputs:
        raise SystemExit("summary output must not overwrite an input export")
    batches = {str(path): read_jsonl(path) for path in args.inputs}
    summary = summarize(batches)
    receipts = [{"path": str(path), "sha256": sha256_path(path)} for path in args.inputs]
    write_atomic(args.json, json.dumps(summary, ensure_ascii=False, indent=2) + "\n")
    write_atomic(args.markdown, render_markdown(summary, receipts))
    print(f"summarized {summary['snapshot_records']} rows across {summary['snapshot_count']} snapshot files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
